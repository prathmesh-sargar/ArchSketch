import { Node, Edge } from '@xyflow/react';
import { TableNodeData, ServiceNodeData, ColumnDefinition } from '../types/schema';

/**
 * Dynamically generates production-ready PostgreSQL DDL from active canvas nodes and relationship edges.
 */
export function generatePostgresDDL(projectName: string, nodes: Node[], edges: Edge[]): string {
  // 1. Separate table nodes and service nodes
  const tableNodes = nodes.filter((n) => n.type === 'tableNode');
  const serviceNodes = nodes.filter((n) => n.type === 'serviceNode');

  if (tableNodes.length === 0) {
    return `-- Generated by ArchSketch for ${projectName}
-- No relational tables currently found on this canvas.
-- Drag tables from the toolbar onto the canvas to generate PostgreSQL DDL.`;
  }

  const lines: string[] = [];

  // Header comment
  lines.push(`-- ==========================================================`);
  lines.push(`-- ArchSketch PostgreSQL Production DDL`);
  lines.push(`-- Workspace: ${projectName}`);
  lines.push(`-- Generated: ${new Date().toISOString()}`);
  lines.push(`-- ==========================================================`);
  lines.push(``);

  // Check if any column uses UUID
  const hasUUID = tableNodes.some((node) => {
    const data = node.data as unknown as TableNodeData;
    return (data.columns || []).some((col) => col.type === 'UUID');
  });

  if (hasUUID) {
    lines.push(`-- Required Extension for UUID generation`);
    lines.push(`CREATE EXTENSION IF NOT EXISTS "uuid-ossp";`);
    lines.push(`CREATE EXTENSION IF NOT EXISTS "pgcrypto";`);
    lines.push(``);
  }

  // Optional: Document Distributed Services & Architecture Topology
  if (serviceNodes.length > 0) {
    lines.push(`-- ----------------------------------------------------------`);
    lines.push(`-- System Architecture Topology & Microservice Map:`);
    serviceNodes.forEach((svcNode) => {
      const data = svcNode.data as unknown as ServiceNodeData;
      const svcName = data.serviceName || (svcNode.data as any).name || 'Microservice';
      const role = data.type || (svcNode.data as any).role || 'Service';
      const proto = (svcNode.data as any).protocol || (svcNode.data as any).techStack || 'HTTP / gRPC';
      lines.push(`--  • ${svcName} [${role.toUpperCase()}] → ${proto}`);
    });
    lines.push(`-- ----------------------------------------------------------`);
    lines.push(``);
  }

  // Map tableId -> tableName for foreign key lookups
  const tableMap = new Map<string, { name: string; data: TableNodeData }>();
  tableNodes.forEach((node) => {
    const data = node.data as unknown as TableNodeData;
    const name = data.tableName?.trim() || `table_${node.id}`;
    tableMap.set(node.id, { name, data });
  });

  // Track generated indexes
  const indexStatements: string[] = [];

  // 2. Build DDL for each table
  tableNodes.forEach((node) => {
    const data = node.data as unknown as TableNodeData;
    const rawTableName = data.tableName?.trim() || `table_${node.id}`;
    const sanitizedTableName = rawTableName.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
    const columns: ColumnDefinition[] = data.columns || [];

    lines.push(`-- Table: ${sanitizedTableName}`);
    lines.push(`CREATE TABLE IF NOT EXISTS "${sanitizedTableName}" (`);

    const columnDefs: string[] = [];
    const tableConstraints: string[] = [];

    // Columns
    columns.forEach((col) => {
      const colName = col.name?.trim().replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase() || 'column';
      let colType = col.type || 'VARCHAR(255)';

      // Convert SQL DataType to proper PostgreSQL syntax
      let colDef = `  "${colName}" ${colType}`;

      // Primary Key constraints
      if (col.isPrimaryKey) {
        if (colType === 'UUID') {
          colDef += ` PRIMARY KEY DEFAULT gen_random_uuid()`;
        } else if (colType === 'INT' || colType === 'BIGINT') {
          // If not SERIAL, still set as primary key
          colDef += ` PRIMARY KEY`;
        } else {
          colDef += ` PRIMARY KEY`;
        }
      } else {
        // Unique constraint
        if (col.isUnique) {
          colDef += ` UNIQUE`;
        }
        // Nullable constraint
        if (col.isNullable === false) {
          colDef += ` NOT NULL`;
        }
        // Smart defaults based on common column patterns
        if (col.defaultValue) {
          colDef += ` DEFAULT ${col.defaultValue}`;
        } else if (colType === 'TIMESTAMP' && (colName.includes('created') || colName.includes('updated'))) {
          colDef += ` DEFAULT CURRENT_TIMESTAMP`;
        } else if (colType === 'BOOLEAN' && (colName.startsWith('is_') || colName.startsWith('has_'))) {
          colDef += ` DEFAULT false`;
        }
      }

      columnDefs.push(colDef);

      // Create index recommendation for foreign keys or search fields
      if (col.isForeignKey || colName.endsWith('_id')) {
        indexStatements.push(
          `CREATE INDEX IF NOT EXISTS "idx_${sanitizedTableName}_${colName}" ON "${sanitizedTableName}"("${colName}");`
        );
      }
    });

    // Foreign Keys inferred from Canvas Edges
    const incomingEdges = edges.filter((e) => e.target === node.id);
    incomingEdges.forEach((edge) => {
      const sourceTableInfo = tableMap.get(edge.source);
      if (sourceTableInfo) {
        const sourceTableName = sourceTableInfo.name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
        
        // Find which column in this table is the foreign key
        // Check handle format: e.g., 'col-in-<colId>'
        let targetColName = '';
        if (edge.targetHandle) {
          const colId = edge.targetHandle.replace('col-in-', '');
          const matchCol = columns.find((c) => c.id === colId);
          if (matchCol) targetColName = matchCol.name;
        }

        // Fallback: look for a column named `${sourceTableName}_id` or with isForeignKey
        if (!targetColName) {
          const matchingCol = columns.find(
            (c) => c.name.toLowerCase() === `${sourceTableName}_id` || c.isForeignKey
          );
          if (matchingCol) targetColName = matchingCol.name;
        }

        if (targetColName) {
          const cleanTargetCol = targetColName.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
          const fkConstraintName = `fk_${sanitizedTableName}_${cleanTargetCol}`;
          tableConstraints.push(
            `  CONSTRAINT "${fkConstraintName}" FOREIGN KEY ("${cleanTargetCol}") REFERENCES "${sourceTableName}"("id") ON DELETE CASCADE`
          );
        }
      }
    });

    // Combine columns and table constraints
    const allDefs = [...columnDefs, ...tableConstraints];
    lines.push(allDefs.join(',\n'));
    lines.push(`);`);
    lines.push(``);
  });

  // 3. Add Indexes
  if (indexStatements.length > 0) {
    lines.push(`-- Foreign Key & Performance Indexes`);
    indexStatements.forEach((idx) => lines.push(idx));
    lines.push(``);
  }

  lines.push(`-- ArchSketch DDL Generation Complete (${tableNodes.length} tables, ${edges.length} relations)`);
  return lines.join('\n');
}
